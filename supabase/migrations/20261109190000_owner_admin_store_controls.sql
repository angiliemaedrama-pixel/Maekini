create or replace function public.place_store_order(
    p_customer_name text,
    p_phone text,
    p_shipping_address text,
    p_payment_method text,
    p_items jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_item_count integer;
    v_input_count integer;
    v_subtotal numeric(12, 2);
    v_items jsonb;
    v_order_id uuid;
begin
    if v_user_id is null then
        raise exception 'Sign in before placing an order.';
    end if;

    if char_length(btrim(coalesce(p_customer_name, ''))) not between 1 and 120
        or char_length(btrim(coalesce(p_phone, ''))) not between 5 and 40
        or char_length(btrim(coalesce(p_shipping_address, ''))) not between 5 and 1000 then
        raise exception 'Enter a valid name, phone number, and shipping address.';
    end if;

    if p_payment_method not in ('Maya', 'GCash', 'COD', 'Credit Card') then
        raise exception 'Choose a supported payment method.';
    end if;

    if p_items is null or jsonb_typeof(p_items) <> 'array' then
        raise exception 'Your cart is empty or contains too many items.';
    end if;

    if jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 30 then
        raise exception 'Your cart is empty or contains too many items.';
    end if;

    select
        count(*),
        coalesce(sum(product.price * item.qty), 0),
        jsonb_agg(jsonb_build_object(
            'id', product.id,
            'name', product.name,
            'price', product.price,
            'qty', item.qty,
            'image_url', product.image_url
        ) order by product.id)
    into v_item_count, v_subtotal, v_items
    from jsonb_to_recordset(p_items) as item(id integer, qty integer)
    join public.store_products as product
        on product.id = item.id
        and product.is_active
    where item.qty between 1 and 20;

    select count(*) into v_input_count
    from jsonb_to_recordset(p_items) as item(id integer, qty integer);

    if v_item_count <> v_input_count then
        raise exception 'A cart item is unavailable or has an invalid quantity. Refresh and try again.';
    end if;

    insert into public.store_orders (
        order_number,
        user_id,
        customer_name,
        phone,
        shipping_address,
        payment_method,
        subtotal,
        shipping,
        total,
        items
    )
    values (
        'MK' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8)),
        v_user_id,
        btrim(p_customer_name),
        btrim(p_phone),
        btrim(p_shipping_address),
        p_payment_method,
        v_subtotal,
        case when v_subtotal > 0 then 79 else 0 end,
        v_subtotal + case when v_subtotal > 0 then 79 else 0 end,
        v_items
    )
    returning id into v_order_id;

    return v_order_id;
end;
$$;

revoke all on function public.place_store_order(text, text, text, text, jsonb) from public, anon;
grant execute on function public.place_store_order(text, text, text, text, jsonb) to authenticated;
