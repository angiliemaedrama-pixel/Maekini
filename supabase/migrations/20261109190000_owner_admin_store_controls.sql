    add column if not exists email text,
    add column if not exists role text not null default 'customer';

do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conrelid = 'public.profiles'::regclass
            and conname = 'profiles_role_check'
    ) then
        alter table public.profiles
            add constraint profiles_role_check
            check (role in ('customer', 'owner'));
    end if;
end;
$$;

update public.profiles as profile
set email = auth_user.email
from auth.users as auth_user
where auth_user.id = profile.id
    and profile.email is distinct from auth_user.email;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.profiles (id, full_name, email, role)
    values (
        new.id,
        coalesce(
            nullif(left(btrim(new.raw_user_meta_data ->> 'full_name'), 120), ''),
            nullif(left(split_part(coalesce(new.email, ''), '@', 1), 120), ''),
            'MaeKini customer'
        ),
        new.email,
        case
            when lower(coalesce(new.email, '')) = 'angiliemaedrama@gmail.com' then 'owner'
            else 'customer'
        end
    );

    return new;
end;
$$;

create or replace function public.is_store_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.profiles
        where id = (select auth.uid())
            and role = 'owner'
    );
$$;

revoke all on function public.is_store_owner() from public, anon;
grant execute on function public.is_store_owner() to anon, authenticated;

do $$
begin
    if not exists (
        select 1 from pg_policies
        where schemaname = 'public'
            and tablename = 'profiles'
            and policyname = 'Store owner can read customer profiles'
    ) then
        create policy "Store owner can read customer profiles"
            on public.profiles
            for select
            to authenticated
            using (public.is_store_owner());
    end if;
end;
$$;

insert into public.profiles (id, full_name, email, role)
select
    auth_user.id,
    coalesce(
        nullif(left(btrim(auth_user.raw_user_meta_data ->> 'full_name'), 120), ''),
        nullif(left(split_part(coalesce(auth_user.email, ''), '@', 1), 120), ''),
        'MaeKini owner'
    ),
    auth_user.email,
    'owner'
from auth.users as auth_user
where lower(auth_user.email) = 'angiliemaedrama@gmail.com'
on conflict (id) do update
set email = excluded.email,
    role = 'owner';

